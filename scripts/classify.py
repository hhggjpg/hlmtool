#
# 【为什么改成"关键词归类"】
# 5 回时，模型的标签总共才几十种，逐个写死就行（旧版本就是这么做的）。
# 但 120 回时，模型自由生成了 1000 多种标签，"逐字匹配"的字典根本配不完
# （前 200 个标签加起来才覆盖 46%）。
# 所以改成"看标签里含有什么关键词"来判类，覆盖面大得多。

