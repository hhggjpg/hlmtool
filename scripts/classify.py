    # ---- 主仆（含依附、下属、雇佣）----
    ("主仆", ["主仆", "主子", "丫鬟", "丫头", "使唤", "服侍", "伏侍", "伺候",
              "奶娘", "乳母", "家奴", "奴仆", "仆人", "小厮", "门子", "管家",
              "侍奉", "陪伴", "跟随", "随从", "下属", "部下", "差役", "庄头",
              "买来", "收房", "家生子", "看门", "为奴"]),

    # ---- 社会（朋友、师徒、同僚、一般交往）----
    ("社会", ["朋友", "好友", "师徒", "师父", "徒弟", "弟子", "同僚", "同事", "同乡",
              "邻居", "邻里", "房东", "租客", "相熟", "相识", "交往", "结交", "知己",
              "贫贱之交", "世交", "同年", "共事", "往来", "介绍", "引荐", "推荐",
              "结拜", "兄弟相称", "姐妹相称", "同窗", "同学", "宾客", "客人",
              "君臣", "上级", "下属关系", "官员", "官吏"]),

    # ---- 冲突（对抗、加害、争夺）----
    ("冲突", ["凶手", "死者", "拐卖", "买主", "争夺", "争斗", "打架", "打伤", "打死",
              "责骂", "训斥", "苛待", "虐待", "陷害", "谋害", "欺压", "欺凌",
              "对头", "仇", "怨恨", "不忿", "嫉妒", "排挤", "冲突", "矛盾", "逼迫",
              "强占", "强娶", "骗", "偷", "抢夺", "告状", "弹劾", "抄家", "骂"]),

    # ---- 情感（亲密、爱慕、怜爱）----
    ("情感", ["爱情", "爱慕", "爱恋", "钟情", "相恋", "情侣", "恋人",
              "怜爱", "疼爱", "宠爱", "溺爱", "喜爱", "亲密", "相好", "情投",
              "知心", "倾心", "思念", "牵挂", "相伴", "依恋", "情深", "相惜"]),

    # ---- 称谓（只是"怎么称呼"，不是真实关系，属于噪音，不画图）----
    ("称谓", ["称谓", "称呼", "名叫", "叫作", "别号", "乳名", "小名", "自谓",
              "称宝", "称林", "称姐姐", "称妹妹", "称二爷"]),
