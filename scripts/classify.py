# 单独处理：这些是"一次性动作/事件"，不是持续关系，不画图
EVENT_WORDS = ["吩咐", "差遣", "回话", "告知", "告诉", "说给", "问答", "问话",
               "请安", "打发", "嘱咐", "叮嘱", "转交", "传送",
               "赠物", "赠送", "送花", "带领", "照看", "资助", "拜访", "交谈",
               "收留", "命名", "灌溉", "还泪", "携入", "成姻", "嘱托",
               "哄", "唤", "同生日", "曾在一处", "所属", "拉手",
               "唱曲", "欲娶", "求娶", "提亲", "议亲", "定亲", "婚配", "出殡",
               "祭奠", "设宴", "宴请", "看戏", "赏花", "作诗", "联句", "读书",
               "命", "请", "求", "送", "赠", "问"]

GRAPH_CATEGORIES = {"亲属", "主仆", "社会", "冲突", "情感"}   # 这些才画进图


def classify(label):
    """给一个自由标签判类别：先看事件，再按 RULES 顺序找关键词"""
    for w in EVENT_WORDS:
        if w in label:
            return "事件"
    for cat, words in RULES:
        for w in words:
            if w in label:
                return cat
    return "未分类"


# ==================== 1. 读 关系表.csv，归类 ====================
rows = []
统计 = {}

with open("output/关系表.csv", encoding="utf-8-sig", newline="") as fi:
    for row in csv.DictReader(fi):
        t = row["关系类型"]
        cat = classify(t)
        rows.append({
            "人物A": row["人物A"],
            "人物B": row["人物B"],
            "原标签": t,
            "类别": cat,
            "出现在第几回": row["出现在第几回"],
            "原文依据": row["原文依据"],
            "上图": "是" if cat in GRAPH_CATEGORIES else "否",
        })
        统计[cat] = 统计.get(cat, 0) + 1

# ==================== 2. 报告 ====================
print("=== 归类结果（共", len(rows), "条）===")
for cat in sorted(统计, key=lambda x: 统计[x], reverse=True):
    marker = "★画图" if cat in GRAPH_CATEGORIES else "  不画图"
    print("  %-6s %5d 条  %s" % (cat, 统计[cat], marker))

可画图 = sum(v for k, v in 统计.items() if k in GRAPH_CATEGORIES)
print("")
print("可画图的关系:", 可画图, "条（占 %.1f%%）" % (可画图 * 100.0 / len(rows)))

未分类 = [r for r in rows if r["类别"] == "未分类"]
if 未分类:
    print("")
    print("⚠️ 仍有", len(未分类), "条没归类。出现最多的标签：")
    去重 = []
    for r in 未分类:
        if r["原标签"] not in 去重:
            去重.append(r["原标签"])
    print("   ", " / ".join(去重[:25]))
else:
    print("")
    print("✅ 全部标签都已归类")

# ==================== 3. 写出分类表 ====================
with open("output/关系表_分类.csv", "w", encoding="utf-8-sig", newline="") as fo:
    w = csv.writer(fo)
    w.writerow(["人物A", "人物B", "类别", "原标签", "出现在第几回", "上图", "原文依据"])
    for r in rows:
        w.writerow([r["人物A"], r["人物B"], r["类别"], r["原标签"],
                    r["出现在第几回"], r["上图"], r["原文依据"]])

print("")
print("已写出 output/关系表_分类.csv")
